# TEST CASE 17 — SECURITY: Command Injection via subprocess & os.system
# Severity: HIGH
# Attack: User input passed to shell command allows arbitrary command execution
# Real impact: Full system compromise, data exfiltration, ransomware

import subprocess
import os

# VULNERABILITY 1: os.system with user input
def ping_host(hostname):
    """DANGEROUS: hostname could contain shell metacharacters."""
    command = f"ping -n 1 {hostname}"
    os.system(command)         # os.system — HIGH vulnerability

# VULNERABILITY 2: subprocess with shell=True and user input
def run_grep(search_term, filename):
    """DANGEROUS: shell=True with user-controlled input."""
    cmd = f"grep {search_term} {filename}"
    result = subprocess.run(cmd, shell=True, capture_output=True, text=True)  # shell injection
    return result.stdout

# VULNERABILITY 3: Concatenating user input into shell command
def convert_file(input_file, output_format):
    """DANGEROUS: format parameter not sanitized."""
    cmd = "convert " + input_file + " -format " + output_format + " output"
    subprocess.call(cmd, shell=True)   # shell injection via concatenation

# VULNERABILITY 4: os.popen with user data
def get_file_info(filepath):
    return os.popen(f"stat {filepath}").read()   # os.popen — HIGH vulnerability

# Attack examples:
safe_host = "google.com"
attack_host = "google.com; del /f /s /q C:\\*"  # Windows command injection
attack_host2 = "google.com && shutdown /s /t 0"   # shutdown injection

print("Safe ping:")
ping_host(safe_host)

# DO NOT run:
# ping_host(attack_host)   # would delete files
# ping_host(attack_host2)  # would shut down system

# SAFE ALTERNATIVES:
def ping_safe(hostname):
    # Safe: use list form (no shell), validate input
    import re
    if not re.match(r'^\[a-zA-Z0-9\.-\]+$', hostname):
        raise ValueError(f"Invalid hostname: {hostname}")
    result = subprocess.run(
        ["ping", "-n", "1", hostname],  # list form — no shell injection
        capture_output=True, text=True, timeout=5
    )
    return result.returncode

print("Safe ping result:", ping_safe("localhost"))

