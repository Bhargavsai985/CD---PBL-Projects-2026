# VULNERABILITY 1: Catastrophic Backtracking Regular Expression (ReDoS)
# Exponential time complexity O(2^n) on non-matching payloads like "aaaaaaaaaaaaaaaaaaaa!"
EVIL_EMAIL_REGEX = re.compile(r"^([a-zA-Z0-9_\-]+)+@([a-zA-Z0-9_\-]+)+$")

def validate_user_input(text: str):
    # HIGH: An attacker submits 25 characters to freeze the server process CPU at 100%
    return EVIL_EMAIL_REGEX.match(text)

# VULNERABILITY 2: Zip / Tar Slip Arbitrary File Overwrite
def unpack_uploaded_plugin(archive_path: str, extract_to: str):
    # HIGH: If archive contains "../../../../bin/exploit", extractall overwrites it
    with zipfile.ZipFile(archive_path, 'r') as zip_ref:
        zip_ref.extractall(extract_to)

def unpack_tar(tar_path: str, dest: str):
    # HIGH: Tar slip directory escape
    with tarfile.open(tar_path) as tar:
        tar.extractall(dest)

# VULNERABILITY 3: Permissive world-writable file permissions (chmod 777)
def create_shared_cache(cache_file: str):
    # HIGH: 0o777 allows any unprivileged local process to read and overwrite cache
    os.chmod(cache_file, 0o777)

