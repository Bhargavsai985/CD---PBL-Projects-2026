# CWE: CWE-345 (Insufficient Verification of Authenticity) & CWE-617 (Reachable Assertion)
# Severity: CRITICAL / HIGH
# Description: Setting algorithms=['none'] or verify=False lets attackers forge arbitrary
# user and admin tokens without knowing the secret key. Python assert statements are stripped in -O mode.

import jwt

SECRET = "production_super_secret_key"

# VULNERABILITY 1: JWT signature verification explicitly disabled
def authenticate_user(token: str):
    # CRITICAL: verify=False accepts forged tokens signed with arbitrary or empty keys
    payload = jwt.decode(token, verify=False)
    return payload["user_id"]

# VULNERABILITY 2: Permitting the insecure 'none' algorithm
def parse_bearer_token(token: str):
    # CRITICAL: 'none' algorithm turns JWT into plain unsigned JSON
    return jwt.decode(token, SECRET, algorithms=["HS256", "none"])

# VULNERABILITY 3: Authorization check gated by assert statement
def grant_admin_access(user_role: str):
    # MEDIUM: 'python -O main.py' completely removes assert statements at compile time,
    # granting unauthenticated users admin access unconditionally
    assert user_role == "admin", "Access denied: Administrator privilege required."
    return "ACCESS_GRANTED_TO_SYSTEM_CONFIG"

