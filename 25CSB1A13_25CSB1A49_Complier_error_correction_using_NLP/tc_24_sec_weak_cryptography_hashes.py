# TEST CASE 24 — SECURITY: Broken Cryptographic Hashes & Ciphers
# CWE: CWE-328 (Broken Hash) & CWE-327 (Broken Cipher Algorithm)
# Severity: HIGH
# Description: MD5 and SHA-1 suffer from collision and length-extension attacks.
# ECB mode encrypts identical plaintext blocks identically, leaking visual/data patterns.

import hashlib
from Crypto.Cipher import AES, DES

# VULNERABILITY 1: Broken hash algorithm (MD5) used for password hashing
def hash_user_password(password: str) -> str:
    # HIGH: MD5 is collision-vulnerable and trivial to reverse via rainbow tables
    return hashlib.md5(password.encode()).hexdigest()

# VULNERABILITY 2: Deprecated hash algorithm (SHA-1)
def compute_checksum(data: bytes) -> str:
    # MEDIUM: SHA-1 is cryptographically deprecated by NIST
    return hashlib.sha1(data).hexdigest()

# VULNERABILITY 3: Insecure Block Cipher Mode (ECB Mode)
def encrypt_credit_card(key: bytes, plaintext: bytes) -> bytes:
    # HIGH: Electronic Codebook (ECB) mode preserves patterns in ciphertext
    cipher = AES.new(key, AES.MODE_ECB)
    return cipher.encrypt(plaintext)

# VULNERABILITY 4: Deprecated 56-bit DES cipher
def legacy_encrypt(key: bytes, message: bytes) -> bytes:
    # HIGH: DES key length is too short; vulnerable to brute-force key search
    cipher = DES.new(key)
    return cipher.encrypt(message)

# SAFE MITIGATION:
# Use hashlib.sha256() or bcrypt/argon2 for passwords.
# Use AES-GCM (AES.MODE_GCM) with random 96-bit nonce.

