# TEST CASE 08 — ZeroDivisionError
# Error: Division by zero in multiple places
# Expected: ZeroDivisionError: division by zero

def compute_stats(values):
    if not values:
        total = 0
        count = 0
        return total / count      # <-- ZeroDivisionError when list is empty

    total = sum(values)
    count = len(values)
    mean = total / count

    # Coefficient of variation
    std_dev = (sum((x - mean) ** 2 for x in values) / count) ** 0.5
    cv = (std_dev / mean) * 100   # <-- ZeroDivisionError if mean == 0

    return {"mean": mean, "std_dev": std_dev, "cv": cv}

print(compute_stats([]))          # triggers first ZeroDivisionError
print(compute_stats([0, 0, 0]))   # triggers second ZeroDivisionError

