# TEST CASE 14 — SECURITY: SQL Injection
# Severity: CRITICAL / HIGH
# Attack: Injecting SQL code through user input to manipulate database queries
# Real impact: Data breach, authentication bypass, data deletion

import sqlite3

# VULNERABILITY 1: String formatting in SQL query (classic injection)
def get_user_unsafe(username):
    conn = sqlite3.connect(":memory:")
    cursor = conn.cursor()
    cursor.execute("CREATE TABLE users (id INT, username TEXT, password TEXT, role TEXT)")
    cursor.execute("INSERT INTO users VALUES (1, 'admin', 'secret123', 'admin')")
    cursor.execute("INSERT INTO users VALUES (2, 'alice', 'pass456', 'user')")
    conn.commit()

    # DANGEROUS: Direct string interpolation in SQL
    query = f"SELECT * FROM users WHERE username = '{username}'"   # SQL injection
    cursor.execute(query)
    return cursor.fetchall()

# VULNERABILITY 2: % formatting
def login_check(username, password):
    conn = sqlite3.connect(":memory:")
    cursor = conn.cursor()
    # DANGEROUS: % formatting in SQL
    query = "SELECT * FROM users WHERE username='%s' AND password='%s'" % (username, password)
    cursor.execute(query)   # SQL injection via % format
    return cursor.fetchone()

# VULNERABILITY 3: Concatenation
def search_products(keyword):
    conn = sqlite3.connect(":memory:")
    cursor = conn.cursor()
    # DANGEROUS: concatenation
    query = "SELECT * FROM products WHERE name LIKE '%" + keyword + "%'"  # SQL injection
    cursor.execute(query)

# Attack payload examples:
attack1 = "admin' OR '1'='1"        # bypasses password check
attack2 = "x'; DROP TABLE users; --"  # drops the table

print("Normal query:", get_user_unsafe("alice"))
# print("Injected query:", get_user_unsafe(attack1))  # would return ALL users

# SAFE ALTERNATIVE: Parameterized queries
def get_user_safe(username):
    conn = sqlite3.connect(":memory:")
    cursor = conn.cursor()
    cursor.execute("CREATE TABLE users (id INT, username TEXT)")
    cursor.execute("INSERT INTO users VALUES (1, 'alice')")
    conn.commit()
    # SAFE: parameterized query - never vulnerable to injection
    cursor.execute("SELECT * FROM users WHERE username = ?", (username,))
    return cursor.fetchall()

print("Safe query:", get_user_safe("alice"))
print("Safe injection attempt:", get_user_safe(attack1))  # returns nothing

