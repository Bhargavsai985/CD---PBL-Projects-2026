import random
import time

# VULNERABILITY 1: Predictable PRNG used for security tokens & password resets
def generate_reset_token() -> str:
    # HIGH: Predictable PRNG allows attackers to forecast reset tokens
    token = f"{random.randint(100000, 999999)}"
    return token

def generate_session_id() -> str:
    # HIGH: random.choice() is not cryptographically secure
    chars = "abcdefghijklmnopqrstuvwxyz0123456789"
    return "".join(random.choice(chars) for _ in range(32))

# VULNERABILITY 2: Timing attack in secret verification
def verify_admin_key(user_key: str, real_key: str) -> bool:
    # MEDIUM: '==' terminates early on the first mismatched character,
    # leaking key bytes via sub-millisecond execution timing differences
    if user_key == real_key:
        return True
    return False

