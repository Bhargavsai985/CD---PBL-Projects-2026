# SAFE ALTERNATIVES:
def safe_read_file(filename):
    # Sanitize: strip path components
    safe_name = os.path.basename(filename)
    if not safe_name.endswith((".txt", ".py", ".csv")):
        raise ValueError("File type not allowed")
    base_dir = "/uploads"
    full_path = os.path.realpath(os.path.join(base_dir, safe_name))
    if not full_path.startswith(base_dir):  # prevent traversal
        raise PermissionError("Access denied")
    return full_path

def safe_discount(pct):
    pct = float(pct)
    if not (0 <= pct <= 100):
        raise ValueError(f"Discount must be 0-100%, got {pct}%")
    return 100.0 * (1 - pct / 100)

