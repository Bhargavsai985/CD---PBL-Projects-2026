    // ── Grade Entry ────────────────────────────────────────────────
    static class GradeEntry {
        private String subject;
        private int    marks;
        private int    maxMarks;

        public GradeEntry(String subject, int marks, int maxMarks) {
            this.subject  = subject;
            this.marks    = marks;
            this.maxMarks = maxMarks;
        }

        public double getPercentage() {
            return (marks * 100.0) / maxMarks;
        }

        public String getGrade() {
            double pct = getPercentage();
            if (pct >= 90) return "A+";
            if (pct >= 80) return "A";
            if (pct >= 70) return "B";
            if (pct >= 60) return "C";
            if (pct >= 50) return "D";
            return "F";
        }

        public String getSubject() { return subject; }
        public int    getMarks()   { return marks;   }

        @Override
        public String toString() {
            return String.format("%-20s %3d/%3d  (%.1f%%) Grade: %s",
                subject, marks, maxMarks, getPercentage(), getGrade());
        }
    }

    // ── Student ────────────────────────────────────────────────────
    static class Student {
        private String         rollNo;
        private String         name;
        private List<GradeEntry> grades;

        public Student(String rollNo, String name) {
            this.rollNo = rollNo;
            this.name   = name;
            this.grades = new ArrayList<>();
        }

        public void addGrade(GradeEntry entry) {
            grades.add(entry);
        }

        public double getCGPA() {
            if (grades.isEmpty()) return 0.0;
            double total = 0;
            for (GradeEntry g : grades) total += g.getPercentage();
            return total / grades.size() / 10.0;
        }

        public String getName()   { return name;   }
        public String getRollNo() { return rollNo; }

        public GradeEntry getTopSubject() {
            return Collections.max(grades,
                Comparator.comparingDouble(GradeEntry::getPercentage));
        }

        public void printReport() {
            System.out.println("\n=== Report Card: " + rollNo + " — " + name + " ===");
            for (GradeEntry g : grades) System.out.println("  " + g);
            System.out.printf("  CGPA: %.2f | Top Subject: %s%n",
                getCGPA(), getTopSubject().getSubject());
        }
    }

    // ── Department ────────────────────────────────────────────────
    static class Department {
        private String          name;
        private List<Student>   students;

        public Department(String name) {
            this.name     = name;
            this.students = new ArrayList<>();
        }

        public void enroll(Student s) { students.add(s); }

        public Student getTopper() {
            return Collections.max(students,
                Comparator.comparingDouble(Student::getCGPA));
        }

        public Map<String, Double> getCGPAMap() {
            Map<String, Double> map = new HashMap<>();
            for (Student s : students) map.put(s.getName(), s.getCGPA());
            return map;
        }
    }

